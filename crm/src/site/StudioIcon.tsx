export type StudioIconName = keyof typeof ICONS;

const VARIANT = { classic: 0, line: 1, soft: 2, solid: 3 } as const;

/** Familia de iconos que usa ahora el panel ('classic' si no sigue el estilo de la web). */
function useIconStyle() {
  const { config } = useSite();
  return panelLook(config).icons;
}

interface StudioIconProps extends SvgIconProps {
  name: StudioIconName;
  /** Forzar una familia (vistas previas); por defecto, la del panel */
  iconStyle?: keyof typeof VARIANT;
}

/** Icono del panel en la familia del estudio. */
export default function StudioIcon({ name, iconStyle, ...props }: StudioIconProps) {
  const current = useIconStyle();
  const Comp = ICONS[name][VARIANT[iconStyle || current]];
  return <Comp {...props} />;
}
